/*
 * P2661 [NOIP 2015 提高组] 信息传递
 * ---------------------------------------------------------------------------
 * 题意压缩：
 *   n 个同学，每人有一个固定的"信息传递对象" to[i]（第 i 个人只会把信息传给 to[i]）。
 *   第 0 轮每人只知道自己生日。之后每一轮，所有人【同时】把自己当前掌握的所有
 *   生日信息告诉 to[i]。问：最少经过多少轮，会有人从别人口中得知"自己的"生日？
 *
 * 把游戏翻译成图：
 *   每个点 i 连一条【有向边】i -> to[i]。因为每人只有一个传递对象，
 *   每点出度恰为 1 —— 这就是一张【函数图】（functional graph，n 点 n 边）。
 *
 * 关键观察：
 *   1) 信息沿有向边 i -> to[i] 一轮走一步。
 *      "u 在第 t 轮听到自己的生日" ⇔ 存在一条从 u 出发、走 t 步回到 u 的闭合路径
 *      ⇔ u 落在某个长度恰为 t 的有向环上。
 *   2) 函数图的每个弱连通分量【恰有一个环】（n 点 n 边、出度全 1 的经典性质）。
 *      不在环上的点都是"指向环的树"，信息最终一定会流进环里。
 *   3) 于是答案 = 图中【最短有向环的长度】（最短的那个环决定游戏第几轮结束）。
 *
 * 算法（O(n)，无递归）：
 *   对每个尚未处理的点，沿 to[] 一路走下去，同时给走过的点记下"在本条链上的次序"。
 *     · 走到一个【本条链上刚走过】的点 → 找到了一个环，环长 = 当前步数 - 该点次序。
 *     · 走到一个【已经处理完结】的点 → 本链不产生新环（信息汇入了旧结构）。
 *   所有点只会被走一遍，故总复杂度 O(n)。
 *
 * 数值范围：1 ≤ n ≤ 200000。
 *   n ≤ 2×10^5，环长、深度都 ≤ n，int 足够；本解一律 int。
 *
 * 编译：g++ -static -O2 -std=c++14 solution.cpp -o solution.exe
 *   （本机必须带 -static，否则运行时段错误）
 */
#include <bits/stdc++.h>
using namespace std;

static const int MAXN = 200000 + 5;

int to_[MAXN];    // to_[i] = i 的信息传递对象
int state_[MAXN]; // 0 = 未访问；1 = 在【当前这条链】上；2 = 已处理完结
int depth_[MAXN]; // 在本次链遍历中，该点是第几个被走到的（从 0 开始）
int path_[MAXN];  // 本次链遍历的节点序列，用于走完后统一标记为"已完结"

int main() {
    int n;
    if (scanf("%d", &n) != 1) return 0;
    for (int i = 1; i <= n; ++i) scanf("%d", &to_[i]);

    int ans = n + 1;                       // 答案上界：最长环 ≤ n

    for (int s = 1; s <= n; ++s) {
        if (state_[s] != 0) continue;      // 已经处理过

        /* ---- 从 s 出发走一条链 ---- */
        int len = 0;                       // 本条链已走过的点数
        int u = s;
        while (state_[u] == 0) {
            state_[u] = 1;                 // 标记：在本条链上
            depth_[u] = len;               // 记录次序
            path_[len++] = u;              // 进路径
            u = to_[u];
        }

        /* ---- 出口一：撞回了本条链上的点 → 找到一个环 ---- */
        if (state_[u] == 1) {
            int cycleLen = len - depth_[u];  // 从 u 再次被走到，中间这段就是一个环
            if (cycleLen < ans) ans = cycleLen;
        }
        /* ---- 出口二：state_[u]==2（已完结）→ 本链无新环 ---- */

        /* ---- 把本条链上的点全部标记为"已完结"，之后不再重复走 ---- */
        for (int i = 0; i < len; ++i) state_[path_[i]] = 2;
    }

    printf("%d\n", ans);
    return 0;
}
