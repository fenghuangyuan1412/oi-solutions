/*
 * P11231 [CSP-S 2024] 决斗
 * ---------------------------------------------------------------------------
 * 题意：n 只怪兽，第 i 只攻击力 = 防御力 = a[i]。每回合选两只不同的怪兽 x、y，
 *       让 x 攻击 y：若 a[x] <= a[y] 则无事发生，否则 y 退出游戏。
 *       每只怪兽整场至多攻击一次；当所有未退出的怪兽都攻击过时游戏结束。
 *       问游戏结束时未退出怪兽数量的【最小值】。
 *
 * 关键转化：把"攻击"看成一条有向匹配边 x → y，要求 a[x] > a[y]，
 *           每只怪兽最多当一次 x（攻击者），最多当一次 y（被攻击者）。
 *           于是：
 *             未退出数量 = n - (最多能杀死的怪兽数)
 *           而"最多能杀死多少只"就是二分图最大匹配，在本题的偏序结构下可用贪心求。
 *
 * 贪心（排序 + 双指针）：
 *   把 a 升序排序。用 i 扫"攻击者候选"，j 扫"被攻击目标"。
 *   每当 a[i] > a[j]，就配一对（i 杀 j），i、j 各前进一格；否则 i 前进（这只怪兽攻击力不够，换更大的）。
 *   因为排序后"大的"总在右边，j 只会被追着走，一趟 O(n)。
 *
 *   为什么贪心对：设最优解杀了 k 只。把最优解的 k 条边按"被攻击者"从小到大排序，
 *   其攻击者也就随之从小到大；贪心每一步都取当前能取的最小的两个指针，
 *   归纳可证贪心至少能配出同样多的边，故贪心得到的匹配数也是 k。
 *
 * 数据范围：n <= 10^5，1 <= a[i] <= 10^5，int 够用。
 *
 * 编译：g++ -static -O2 -std=c++14 solution.cpp -o solution.exe
 */
#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n;
    if (!(cin >> n)) return 0;

    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];
    sort(a.begin(), a.end());

    int killed = 0, j = 0;                 // j：当前最小的"还没被杀掉"的目标
    for (int i = 0; i < n; ++i) {          // i：当前攻击者候选
        if (a[i] > a[j]) {                 // 能杀
            ++killed;
            ++j;                           // 这个目标被杀了，换下一个
        }
        // 杀不了就只把 i 前移：换个更大的攻击者再试
    }

    cout << n - killed << "\n";
    return 0;
}
